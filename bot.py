def format_prices(item: dict) -> str:
    vols = item.get("volumes", {}) or {}
    if not vols:
        return ""
    # красиво выводим все варианты
    lines = []
    for k in vols.keys():
        lines.append(f"• {k}")
    return "\n".join(lines)

